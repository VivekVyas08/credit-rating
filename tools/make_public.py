#!/usr/bin/env python3
"""Build a publishable copy of this project, by WHITELIST.

    python make_public.py [--out <dir>] [--force]

WHY A WHITELIST
---------------
The obvious way to prepare a repo is a .gitignore. That is the wrong instrument here, because
this working tree is mostly material that must never be published:

  * ~2,350 rating agency publications and methodology papers (CRISIL/, CareEdge/, Methodology/,
    Report for Reference/, Framework References/, Knowledge Base/) - third-party copyrighted
    documents, about 54 MB;
  * ~190 company annual reports and filings under Companies/*/documents/, about 73 MB;
  * rating rationales generated by this project that name real listed issuers and assign them
    grades - they are not agency opinions and must not be mistaken for any;
  * working notes, drafts and correspondence.

With a blacklist, anything added later is published by default and one forgotten pattern leaks
a document set. With a whitelist, anything added later is withheld by default and the failure
mode is a missing file, not a disclosed one. For this tree that is the only sane direction.

WHAT SHIPS
----------
The verification toolkit and the web app - the parts that are original work, carry no
third-party content, and are useful to someone who has their own documents. Everything else
stays here. Run with --list to see the decision for every top-level entry without copying.
"""

